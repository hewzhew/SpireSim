use serde::Deserialize;
use std::collections::{BTreeMap, BTreeSet};
use std::env;
use std::fs;
use std::path::Path;

const RELIC_IDENTITY_CONTRACT_PATH: &str = "src/content/relics/identity_v1.json";

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct RelicIdentityContract {
    schema_name: String,
    schema_version: u32,
    entries: Vec<RelicIdentityEntry>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct RelicIdentityEntry {
    stable_id: String,
    runtime_symbol: String,
    external_id: String,
    external_aliases: Vec<String>,
}

fn rust_string(value: &str) -> String {
    serde_json::to_string(value).expect("identity string should encode as a Rust string literal")
}

fn normalized_external_id(value: &str) -> String {
    value
        .chars()
        .filter(|character| character.is_ascii_alphanumeric())
        .map(|character| character.to_ascii_lowercase())
        .collect()
}

fn generate_relic_identity(out_dir: &Path) {
    let path = Path::new(RELIC_IDENTITY_CONTRACT_PATH);
    let payload = fs::read_to_string(path).unwrap_or_else(|error| {
        panic!(
            "failed to read {RELIC_IDENTITY_CONTRACT_PATH}; the tracked relic identity contract is required: {error}"
        )
    });
    let contract: RelicIdentityContract = serde_json::from_str(&payload)
        .unwrap_or_else(|error| panic!("invalid {RELIC_IDENTITY_CONTRACT_PATH}: {error}"));
    if contract.schema_name != "RelicIdentityContract" || contract.schema_version != 1 {
        panic!(
            "unsupported relic identity contract {} v{}",
            contract.schema_name, contract.schema_version
        );
    }
    if contract.entries.is_empty() {
        panic!("relic identity contract must not be empty");
    }

    let mut stable_ids = BTreeSet::new();
    let mut runtime_symbols = BTreeSet::new();
    let mut exact_external_ids: BTreeMap<String, String> = BTreeMap::new();
    let mut normalized_external_ids: BTreeMap<String, String> = BTreeMap::new();
    for entry in &contract.entries {
        if entry.stable_id.is_empty()
            || entry.runtime_symbol.is_empty()
            || entry.external_id.is_empty()
        {
            panic!("relic identity fields must not be empty");
        }
        if entry.stable_id.trim() != entry.stable_id
            || entry.stable_id.contains(':')
            || entry.stable_id.chars().any(char::is_control)
        {
            panic!(
                "relic stable ID must be a trimmed entity-key component: {:?}",
                entry.stable_id
            );
        }
        if !entry
            .runtime_symbol
            .chars()
            .next()
            .is_some_and(|character| character.is_ascii_alphabetic())
            || !entry
                .runtime_symbol
                .chars()
                .all(|character| character.is_ascii_alphanumeric() || character == '_')
        {
            panic!(
                "relic runtime symbol is not a Rust identifier: {:?}",
                entry.runtime_symbol
            );
        }
        if !stable_ids.insert(entry.stable_id.clone()) {
            panic!("duplicate relic stable ID: {}", entry.stable_id);
        }
        if !runtime_symbols.insert(entry.runtime_symbol.clone()) {
            panic!("duplicate relic runtime symbol: {}", entry.runtime_symbol);
        }
        for external_id in std::iter::once(&entry.external_id).chain(&entry.external_aliases) {
            if external_id.is_empty() {
                panic!("empty external relic ID for {}", entry.stable_id);
            }
            if let Some(owner) =
                exact_external_ids.insert(external_id.clone(), entry.stable_id.clone())
            {
                panic!(
                    "external relic ID {external_id:?} is shared by {owner} and {}",
                    entry.stable_id
                );
            }
            let normalized = normalized_external_id(external_id);
            if normalized.is_empty() {
                panic!(
                    "external relic ID {external_id:?} has no alphanumeric identity for {}",
                    entry.stable_id
                );
            }
            if let Some(owner) =
                normalized_external_ids.insert(normalized.clone(), entry.stable_id.clone())
            {
                if owner != entry.stable_id {
                    panic!(
                        "normalized external relic ID {normalized:?} is shared by {owner} and {}",
                        entry.stable_id
                    );
                }
            }
        }
    }

    let mut generated = String::from(
        "// AUTO-GENERATED by build.rs from src/content/relics/identity_v1.json\n\
         // DO NOT EDIT MANUALLY\n\n",
    );
    generated.push_str("pub(super) const RELIC_STABLE_IDS_V1: &[&str] = &[\n");
    for entry in &contract.entries {
        generated.push_str(&format!("    {},\n", rust_string(&entry.stable_id)));
    }
    generated.push_str("];\n\n");

    generated.push_str(
        "pub(super) const fn relic_stable_id_v1(id: RelicId) -> &'static str {\n    match id {\n",
    );
    for entry in &contract.entries {
        generated.push_str(&format!(
            "        RelicId::{} => {},\n",
            entry.runtime_symbol,
            rust_string(&entry.stable_id)
        ));
    }
    generated.push_str("    }\n}\n\n");

    generated.push_str(
        "pub(super) const fn relic_stable_ordinal_v1(id: RelicId) -> u16 {\n    match id {\n",
    );
    for (ordinal, entry) in contract.entries.iter().enumerate() {
        generated.push_str(&format!(
            "        RelicId::{} => {},\n",
            entry.runtime_symbol, ordinal
        ));
    }
    generated.push_str("    }\n}\n\n");

    generated.push_str(
        "pub(super) fn relic_id_from_stable_id_v1(stable_id: &str) -> Option<RelicId> {\n    match stable_id {\n",
    );
    for entry in &contract.entries {
        generated.push_str(&format!(
            "        {} => Some(RelicId::{}),\n",
            rust_string(&entry.stable_id),
            entry.runtime_symbol
        ));
    }
    generated.push_str("        _ => None,\n    }\n}\n\n");

    generated.push_str(
        "pub(super) const fn relic_external_id_v1(id: RelicId) -> &'static str {\n    match id {\n",
    );
    for entry in &contract.entries {
        generated.push_str(&format!(
            "        RelicId::{} => {},\n",
            entry.runtime_symbol,
            rust_string(&entry.external_id)
        ));
    }
    generated.push_str("    }\n}\n\n");

    generated.push_str(
        "pub(super) const fn relic_external_aliases_v1(id: RelicId) -> &'static [&'static str] {\n    match id {\n",
    );
    for entry in &contract.entries {
        let aliases = entry
            .external_aliases
            .iter()
            .map(|alias| rust_string(alias))
            .collect::<Vec<_>>()
            .join(", ");
        generated.push_str(&format!(
            "        RelicId::{} => &[{}],\n",
            entry.runtime_symbol, aliases
        ));
    }
    generated.push_str("    }\n}\n\n");

    generated.push_str(
        "pub(super) fn relic_id_from_external_id_exact_v1(external_id: &str) -> Option<RelicId> {\n    match external_id {\n",
    );
    for entry in &contract.entries {
        let patterns = std::iter::once(&entry.external_id)
            .chain(&entry.external_aliases)
            .map(|value| rust_string(value))
            .collect::<Vec<_>>()
            .join(" | ");
        generated.push_str(&format!(
            "        {patterns} => Some(RelicId::{}),\n",
            entry.runtime_symbol
        ));
    }
    generated.push_str("        _ => None,\n    }\n}\n\n");

    fs::write(out_dir.join("generated_relic_identity.rs"), generated)
        .expect("generated relic identity should be writable");
}

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    let profile = env::var("PROFILE").expect("Cargo should provide PROFILE to build.rs");
    println!("cargo:rustc-env=STS_CARGO_PROFILE={profile}");
    let repository_root = fs::canonicalize(
        env::var_os("CARGO_MANIFEST_DIR").expect("Cargo should provide CARGO_MANIFEST_DIR"),
    )
    .expect("repository root should be canonicalizable");
    println!(
        "cargo:rustc-env=STS_REPOSITORY_ROOT={}",
        repository_root.display()
    );
    let out_dir = env::var_os("OUT_DIR").unwrap();
    let out_dir = Path::new(&out_dir);
    println!("cargo:rerun-if-changed={RELIC_IDENTITY_CONTRACT_PATH}");
    generate_relic_identity(out_dir);
}
