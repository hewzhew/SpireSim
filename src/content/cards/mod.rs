pub struct CardDefinition {
    pub id: CardId,
    pub name: &'static str,
    pub card_type: CardType,
    pub rarity: CardRarity,
    pub cost: i8, // -1 for X cost, -2 for unplayable
    pub base_damage: i32,
    pub base_block: i32,
    pub base_magic: i32,
    pub target: CardTarget,
    pub is_multi_damage: bool,
    pub exhaust: bool,
    pub ethereal: bool,
    pub innate: bool,
    pub tags: &'static [CardTag],
    pub upgrade_damage: i32,
    pub upgrade_block: i32,
    pub upgrade_magic: i32,
}

fn build_curse(id: CardId, name: &'static str, cost: i8) -> CardDefinition {
    let mut def = CardDefinition {
        id,
        name,
        card_type: CardType::Curse,
        rarity: CardRarity::Curse,
        cost,
        base_damage: 0,
        base_block: 0,
        base_magic: 0,
        target: CardTarget::None,
        is_multi_damage: false,
        exhaust: false,
        ethereal: false,
        innate: false,
        tags: &[],
        upgrade_damage: 0,
        upgrade_block: 0,
        upgrade_magic: 0,
    };

    if id == CardId::AscendersBane
        || id == CardId::CurseOfTheBell
        || id == CardId::Necronomicurse
        || id == CardId::Pride
    {
        def.rarity = CardRarity::Special;
    }

    if id == CardId::AscendersBane || id == CardId::Clumsy {
        def.ethereal = true;
    }

    if id == CardId::Writhe || id == CardId::Pride {
        def.innate = true;
    }

    if id == CardId::Pride {
        def.exhaust = true;
    }

    def
}

/// Dispatches card-specific logic that natively occurs exactly when a card is exhausted.
/// Base Slay the Spire has only two cards that override `triggerOnExhaust()`:
/// 1. Sentinel (Gain Energy)
/// 2. Necronomicurse (Clone itself back to hand)
pub fn resolve_card_on_exhaust(
    card: &crate::runtime::combat::CombatCard,
    state: &crate::runtime::combat::CombatState,
) -> Vec<crate::runtime::action::ActionInfo> {
    match card.id {
        CardId::Necronomicurse => vec![crate::runtime::action::ActionInfo {
            action: make_constructed_temp_card_in_hand_action(
                CardId::Necronomicurse,
                1,
                false,
                state,
            ),
            insertion_mode: crate::runtime::action::AddTo::Bottom,
        }],
        CardId::Sentinel => vec![crate::runtime::action::ActionInfo {
            action: crate::runtime::action::Action::GainEnergy {
                amount: mechanics::card_energy_gain_v1(card.id, card.upgrades, 0)
                    .expect("Sentinel energy rule")
                    .amount,
            },
            insertion_mode: crate::runtime::action::AddTo::Top,
        }],
        _ => vec![],
    }
}

pub const STARTER_STRIKES: [CardId; 4] = [
    CardId::Strike,
    CardId::StrikeG,
    CardId::StrikeB,
    CardId::StrikeP,
];
pub const STARTER_DEFENDS: [CardId; 4] = [
    CardId::Defend,
    CardId::DefendG,
    CardId::DefendB,
    CardId::DefendP,
];

pub fn is_starter_strike(id: CardId) -> bool {
    STARTER_STRIKES.contains(&id)
}

/// Membership used by tag-sensitive runtime effects, independent of name.
pub fn card_has_tag(id: CardId, tag: CardTag) -> bool {
    get_card_definition(id).tags.contains(&tag)
}

pub fn is_starter_defend(id: CardId) -> bool {
    STARTER_DEFENDS.contains(&id)
}

pub fn is_starter_basic(id: CardId) -> bool {
    is_starter_strike(id) || is_starter_defend(id)
}

pub fn is_innate_card(card: &crate::runtime::combat::CombatCard) -> bool {
    is_innate_card_for(card.id, card.upgrades)
}

pub fn is_innate_card_for(card_id: CardId, upgrades: u8) -> bool {
    get_card_definition(card_id).innate
        || matches!(card_id, CardId::Brutality) && upgrades > 0
        || matches!(card_id, CardId::AfterImage) && upgrades > 0
        || matches!(card_id, CardId::InfiniteBlades) && upgrades > 0
        || matches!(card_id, CardId::Chill) && upgrades > 0
        || matches!(card_id, CardId::HelloWorld) && upgrades > 0
        || matches!(card_id, CardId::MachineLearning) && upgrades > 0
        || matches!(card_id, CardId::Storm) && upgrades > 0
        || matches!(card_id, CardId::BattleHymn) && upgrades > 0
        || matches!(card_id, CardId::Establishment) && upgrades > 0
        || matches!(card_id, CardId::Alpha) && upgrades > 0
}

